#!/usr/bin/env python3
"""Report where Phi's sentences leave structure to the listener.

Every sentence in the lexicon's examples and the active Markdown is parsed
and measured three ways.

* **Readings** (``phi_readings``): the ways each clause divides into subject,
  adjuncts, object, and manner, and the places each dependent clause could
  end. The conservative count lets only nouns, pronouns, and names end a
  phrase freely; the full count also lets an event or quality noun head a
  phrase with modifiers of its own.
* **Open roles** (``phi_roles``): clauses whose one bare phrase may be
  subject or object, because the verb takes an object elsewhere.
* **Third persons** (``phi_roles``): uses of ``shia``, and unsaid subjects,
  while two or more third persons are live in the text.

None of the counts uses meanings, so each is an upper bound on what the
grammar leaves open. None is a rate of misunderstanding.

The committed ledger records one row per file. Continuous integration
regenerates it and fails on any difference, so a change in a text shows up
as a changed row.
"""

from __future__ import annotations

import argparse
from collections import Counter, defaultdict
from dataclasses import dataclass, field
import json
from pathlib import Path
import sys

from phi_readings import ReadingCounter, SentenceReadings
from phi_roles import (
    ReferenceCounts,
    ReferenceTracker,
    object_taking_verbs,
    open_role,
    settled,
)
from phi_sentence_validator import Lexicon, PROJECT_ROOT
import validate_sentences

LEDGER = PROJECT_ROOT / "documents" / "validation" / "phrase_readings_baseline.txt"

GROUP_ORDER = (
    "Translations",
    "Original compositions",
    "Manual",
    "Pamphlets",
    "Primer",
    "Book",
    "Dictionary examples",
    "Other documents",
)
PREFIX_GROUPS = (
    ("manual/", "Manual"),
    ("pamphlets/", "Pamphlets"),
    ("primer/", "Primer"),
    ("book/", "Book"),
    ("vocabulary/", "Dictionary examples"),
)

LEDGER_HEADER = """\
# Phrase-reading ledger
#
# Generated by scripts/audit_phrase_readings.py. Do not edit by hand.
# One row per file; every dictionary example is gathered under vocabulary/.
# The counts are upper bounds on what the grammar leaves open. They use no
# meanings and are not rates of misunderstanding.
#
# sentences   sentences parsed (each quoted sentence counts as one)
# divided     sentences with more than one division into phrases, counting
#             only nouns, pronouns, and names as free phrase ends
# full        the same, also letting an event or quality noun head a phrase
# roles       clauses whose one bare phrase may be subject or object
# relroles    relative clauses whose head may be subject or object
# shia        uses of shia
# contested   uses of shia while two or more third persons are live
# doubled     clauses with two separate shia
#
# Columns: file, sentences, divided, full, roles, relroles, shia, contested, doubled.
"""


@dataclass
class Row:
    path: str
    sentence: SentenceReadings
    roles: list[str] = field(default_factory=list)
    role_verbs: list[str] = field(default_factory=list)
    # Open roles whose phrase is not headed by mia or thia.
    third_person_roles: int = 0
    reference: ReferenceCounts = field(default_factory=ReferenceCounts)


def original_works() -> frozenset[str]:
    catalogue = json.loads((PROJECT_ROOT / "texts" / "catalogue.json").read_text(encoding="utf-8"))
    return frozenset(
        "texts/" + work["path"]
        for work in catalogue.get("works", [])
        if work.get("method", "").lower().startswith("original")
    )


def group_of(path: str, originals: frozenset[str]) -> str:
    if path.startswith("texts/"):
        return "Original compositions" if path in originals else "Translations"
    for prefix, name in PREFIX_GROUPS:
        if path.startswith(prefix):
            return name
    return "Other documents"


def collect(openers: frozenset[str] = frozenset()) -> tuple[list[Row], Counter[str]]:
    """Measure the whole corpus, in document order."""
    lexicon = Lexicon.load()
    counter = ReadingCounter(lexicon, openers=openers)
    sources = list(validate_sentences.iter_lexicon_examples(PROJECT_ROOT))
    sources.extend(
        validate_sentences.iter_markdown_examples(
            PROJECT_ROOT, lexicon, validate_sentences.ACTIVE_DOC_ROOTS
        )
    )
    seen = set()
    rows: list[Row] = []
    for source in sources:
        path = source.label.split(":", 1)[0]
        parts = counter.analyse_sentences(source.text, allow_fragments=source.allow_fragments)
        if parts is None:
            continue
        for part in parts:
            key = (path, part.text)
            if key in seen:
                continue
            seen.add(key)
            rows.append(Row(path, part))

    verbs = object_taking_verbs(row.sentence for row in rows)
    tracker = ReferenceTracker()
    current = None
    for row in rows:
        # Where a dependent clause has several possible ends, the clauses of
        # every alternative are on record, so roles are counted only where
        # the clause structure is settled.
        if settled(row.sentence):
            for clause in row.sentence.clauses:
                kind = open_role(clause, verbs)
                if kind:
                    row.roles.append(kind)
                    row.role_verbs.append(clause.verb)
                    if kind == "main" and clause.bare_heads[0][1] not in {"mia", "thia"}:
                        row.third_person_roles += 1
        if row.path.startswith("vocabulary/"):
            continue
        if row.path != current:
            tracker.reset()
            current = row.path
        row.reference = tracker.observe(row.sentence)
    return rows, verbs


def percent(part: int, whole: int) -> str:
    return f"{100 * part / whole:.0f}%" if whole else "-"


def ledger_key(path: str) -> str:
    return "vocabulary/" if path.startswith("vocabulary/") else path


def render_ledger(rows: list[Row]) -> str:
    by_file: dict[str, list[Row]] = defaultdict(list)
    for row in rows:
        by_file[ledger_key(row.path)].append(row)
    lines = [LEDGER_HEADER]
    for path in sorted(by_file):
        group = by_file[path]
        lines.append(
            "\t".join(
                str(value)
                for value in (
                    path,
                    len(group),
                    sum(1 for r in group if r.sentence.conservative > 1),
                    sum(1 for r in group if r.sentence.full > 1),
                    sum(r.roles.count("main") for r in group),
                    sum(r.roles.count("relative") for r in group),
                    sum(r.reference.third_person_pronouns for r in group),
                    sum(r.reference.contested_pronouns for r in group),
                    sum(r.reference.doubled_clauses for r in group),
                )
            )
        )
    return "\n".join(lines) + "\n"


def render_report(rows: list[Row], verbs: Counter[str], top: int) -> str:
    originals = original_works()
    by_group: dict[str, list[Row]] = defaultdict(list)
    by_file: dict[str, list[Row]] = defaultdict(list)
    for row in rows:
        by_group[group_of(row.path, originals)].append(row)
        by_file[row.path].append(row)

    lines = ["# Phrase-reading audit", "", "## Readings", ""]
    lines += [
        "| Corpus | Sentences | More than one reading | Four or more | "
        "More than one, full count | Outside canonical order | Not modelled |",
        "|---|---:|---:|---:|---:|---:|---:|",
    ]
    for name in GROUP_ORDER:
        group = by_group.get(name)
        if not group:
            continue
        total = len(group)
        many = sum(1 for r in group if r.sentence.conservative > 1)
        four = sum(1 for r in group if r.sentence.conservative >= 4)
        wide = sum(1 for r in group if r.sentence.full > 1)
        relaxed = sum(1 for r in group if any(c.relaxed for c in r.sentence.clauses))
        missed = sum(1 for r in group if r.sentence.unmodelled)
        lines.append(
            f"| {name} | {total} | {many} ({percent(many, total)}) | "
            f"{four} ({percent(four, total)}) | {wide} ({percent(wide, total)}) | "
            f"{relaxed} ({percent(relaxed, total)}) | {missed} ({percent(missed, total)}) |"
        )

    seam_counts: Counter[str] = Counter()
    divided_clauses = 0
    join_open: Counter[str] = Counter()
    join_total: Counter[str] = Counter()
    for row in rows:
        for clause in row.sentence.clauses:
            if clause.conservative > 1 and clause.seams:
                divided_clauses += 1
                seam_counts.update(clause.seams)
        for join in row.sentence.joins:
            join_total[join.kind] += 1
            if join.alternatives > 1:
                join_open[join.kind] += 1
    lines += [
        "",
        f"Clauses with more than one division, conservative count: {divided_clauses}. "
        "A clause may show several kinds of seam.",
        "",
        "| Kind of seam | Clauses |",
        "|---|---:|",
    ]
    for kind, count in seam_counts.most_common():
        lines.append(f"| {kind} | {count} |")
    lines += ["", "| Dependent clause | With more than one possible end | Of |", "|---|---:|---:|"]
    for kind in ("adverbial", "relative"):
        lines.append(f"| {kind} | {join_open[kind]} | {join_total[kind]} |")

    lines += [
        "",
        "## Open roles",
        "",
        f"Verbs the corpus shows with an object: {len(verbs)}.",
        "",
        "| Corpus | Clauses | One bare phrase, subject or object | "
        "Of which not `mia` or `thia` | Relative clauses, head subject or object | "
        "Sentences with either |",
        "|---|---:|---:|---:|---:|---:|",
    ]
    role_verbs: Counter[str] = Counter()
    for name in GROUP_ORDER:
        group = by_group.get(name)
        if not group:
            continue
        clauses = sum(len(r.sentence.clauses) for r in group)
        main = sum(r.roles.count("main") for r in group)
        relative = sum(r.roles.count("relative") for r in group)
        either = sum(1 for r in group if r.roles)
        third = sum(r.third_person_roles for r in group)
        for r in group:
            role_verbs.update(r.role_verbs)
        lines.append(
            f"| {name} | {clauses} | {main} ({percent(main, clauses)}) | {third} | {relative} | "
            f"{either} ({percent(either, len(group))} of sentences) |"
        )
    lines += [
        "",
        "Verbs most often found with an open role: "
        + ", ".join(f"`{verb}` ({count})" for verb, count in role_verbs.most_common(15))
        + ".",
    ]

    lines += [
        "",
        "## Third persons",
        "",
        "| Corpus | Uses of `shia` | While two or more third persons are live | "
        "Clauses with two `shia` | Unsaid subjects | Unsaid while two or more are live |",
        "|---|---:|---:|---:|---:|---:|",
    ]
    for name in GROUP_ORDER:
        group = by_group.get(name)
        if not group or name == "Dictionary examples":
            continue
        uses = sum(r.reference.third_person_pronouns for r in group)
        contested = sum(r.reference.contested_pronouns for r in group)
        doubled = sum(r.reference.doubled_clauses for r in group)
        unsaid = sum(r.reference.unsaid_subjects for r in group)
        unsaid_contested = sum(r.reference.contested_unsaid for r in group)
        lines.append(
            f"| {name} | {uses} | {contested} ({percent(contested, uses)}) | {doubled} | "
            f"{unsaid} | {unsaid_contested} ({percent(unsaid_contested, unsaid)}) |"
        )

    lines += [
        "",
        "## By text",
        "",
        "| File | Sentences | More than one reading | Full count | Open roles | "
        "`shia` | Contested | Two `shia` in a clause |",
        "|---|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for path in sorted(by_file):
        if not path.startswith("texts/"):
            continue
        group = by_file[path]
        total = len(group)
        many = sum(1 for r in group if r.sentence.conservative > 1)
        wide = sum(1 for r in group if r.sentence.full > 1)
        roles = sum(len(r.roles) for r in group)
        uses = sum(r.reference.third_person_pronouns for r in group)
        contested = sum(r.reference.contested_pronouns for r in group)
        doubled = sum(r.reference.doubled_clauses for r in group)
        lines.append(
            f"| `{path}` | {total} | {many} ({percent(many, total)}) | "
            f"{wide} ({percent(wide, total)}) | {roles} | {uses} | "
            f"{contested} ({percent(contested, uses)}) | {doubled} |"
        )

    lines += ["", f"## The {top} sentences with the most readings", ""]
    ranked = sorted(rows, key=lambda r: (-r.sentence.conservative, r.path, r.sentence.text))
    for row in ranked[:top]:
        lines.append(
            f"- {row.sentence.conservative} readings, `{row.path}`: `{row.sentence.text}`"
        )
    return "\n".join(lines) + "\n"


def show_sentence(text: str, openers: frozenset[str]) -> int:
    counter = ReadingCounter(openers=openers)
    parts = counter.analyse_sentences(text)
    if parts is None:
        print("The sentence does not parse.")
        return 1
    for part in parts:
        print(f"{part.text}")
        print(f"  readings: {part.conservative} conservative, {part.full} full")
        for join in part.joins:
            print(
                f"  {join.kind} clause opened by '{join.opener}': "
                f"{join.alternatives} possible end(s)"
            )
        for clause in part.clauses:
            if clause.conservative < 2:
                continue
            print(f"  clause: {clause.text}")
            for division in clause.divisions:
                print(f"    {division}")
            if clause.seams:
                print(f"    open seams: {', '.join(clause.seams)}")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--sentence", help="count one literal Phi sentence and show its divisions")
    parser.add_argument("--paths", nargs="+", help="limit the report to files under these paths")
    parser.add_argument("--report", type=Path, help="write the Markdown report here")
    parser.add_argument("--output", type=Path, help="write the per-file ledger here")
    parser.add_argument(
        "--check", action="store_true", help="fail when the committed ledger is stale"
    )
    parser.add_argument("--top", type=int, default=20, help="how many sentences to list")
    parser.add_argument(
        "--openers",
        nargs="+",
        default=[],
        help="what-if: count as though these Slot 2 words always began a new phrase",
    )
    args = parser.parse_args()
    openers = frozenset(args.openers)

    if args.sentence is not None:
        return show_sentence(args.sentence, openers)

    rows, verbs = collect(openers)
    if args.check or args.output:
        if openers:
            print("the ledger records the language as it is; drop --openers")
            return 2
        ledger = render_ledger(rows)
        if args.check:
            current = LEDGER.read_text(encoding="utf-8") if LEDGER.is_file() else ""
            if current != ledger:
                print(
                    "phrase-reading ledger is stale; run "
                    "python3 scripts/audit_phrase_readings.py --output "
                    "documents/validation/phrase_readings_baseline.txt"
                )
                return 1
            print("phrase-reading ledger is current.")
            return 0
        args.output.write_text(ledger, encoding="utf-8")
        files = len(ledger.splitlines()) - len(LEDGER_HEADER.splitlines())
        print(f"wrote {args.output}: {files} file(s)")
        return 0

    if args.paths:
        rows = [row for row in rows if any(row.path.startswith(path) for path in args.paths)]
    report = render_report(rows, verbs, args.top)
    if args.report:
        args.report.write_text(report, encoding="utf-8")
        print(f"wrote {args.report}")
    else:
        sys.stdout.write(report)
    return 0


if __name__ == "__main__":
    sys.exit(main())
