#!/usr/bin/env python3
"""List sentences that parse but may break canon's word order.

The sentence parser accepts every sentence listed here. Each one also has a
reading under which a manner word stands outside the Slot 1 block (PHL001) or
a direct object stands before a prepositional phrase (PHL002). The parser has
no verb valency, so it cannot choose between the readings; a person can.

The committed ledger records the candidates already seen. Continuous
integration regenerates it and fails on any difference, so a new candidate
shows up in review as one added line.
"""

from __future__ import annotations

import argparse
from collections import Counter
from pathlib import Path
import sys

from phi_sentence_validator import Lexicon, PROJECT_ROOT, PhiParser
import validate_sentences

LEDGER = PROJECT_ROOT / "documents" / "validation" / "sentence_order_baseline.txt"

HEADER = """\
# Sentence-order review ledger
#
# Generated by scripts/audit_sentence_order.py. Do not edit by hand.
# Every sentence below parses. Each also has a reading that breaks canon's
# order, and the parser cannot tell which reading is meant.
#
# PHL001  an adjective stands directly before the Slot 1 stack. As a manner or
#         depictive word it belongs inside the stack, directly before the verb.
#         The order stands when the adjective is a quality noun and the verb's
#         object.
# PHL002  a noun stands between a clause-initial subject pronoun and a
#         prepositional phrase. As a direct object it belongs after the phrase
#         (S PP O V). The order stands when pronoun and noun form one possessed
#         subject.
#
# Columns: code, flagged word, file, occurrences in that file, sentence.
"""


def collect() -> list[tuple[str, str, str, int, str]]:
    lexicon = Lexicon.load()
    parser = PhiParser(lexicon)
    sources = list(validate_sentences.iter_lexicon_examples(PROJECT_ROOT))
    sources.extend(
        validate_sentences.iter_markdown_examples(
            PROJECT_ROOT, lexicon, validate_sentences.ACTIVE_DOC_ROOTS
        )
    )
    counts: Counter[tuple[str, str, str, str]] = Counter()
    seen = set()
    for source in sources:
        key = (source.label, source.text)
        if key in seen:
            continue
        seen.add(key)
        result = parser.parse(source.text, allow_fragments=source.allow_fragments)
        if not result.ok:
            continue
        path = source.label.split(":", 1)[0]
        for advisory in result.advisories:
            start = advisory.token_index
            while start > 0 and result.tokens[start - 1].text != ".":
                start -= 1
            end = advisory.token_index
            while end < len(result.tokens) and result.tokens[end].text != ".":
                end += 1
            sentence = " ".join(token.text for token in result.tokens[start:end]) + "."
            word = result.tokens[advisory.token_index].text
            counts[(advisory.code, word, path, sentence)] += 1
    return sorted(
        (code, word, path, count, sentence)
        for (code, word, path, sentence), count in counts.items()
    )


def render(rows: list[tuple[str, str, str, int, str]]) -> str:
    lines = [HEADER]
    lines.extend(
        f"{code}\t{word}\t{path}\t{count}\t{sentence}"
        for code, word, path, count, sentence in rows
    )
    return "\n".join(lines) + "\n"


def main() -> int:
    argument_parser = argparse.ArgumentParser(description=__doc__)
    argument_parser.add_argument("--output", type=Path, help="write the ledger here")
    argument_parser.add_argument(
        "--check", action="store_true", help="fail when the committed ledger is stale"
    )
    args = argument_parser.parse_args()
    rows = collect()
    text = render(rows)
    if args.check:
        current = LEDGER.read_text(encoding="utf-8") if LEDGER.is_file() else ""
        if current != text:
            print(
                "sentence-order ledger is stale; run "
                "python3 scripts/audit_sentence_order.py --output "
                "documents/validation/sentence_order_baseline.txt"
            )
            return 1
        print("sentence-order ledger is current.")
        return 0
    if args.output:
        args.output.write_text(text, encoding="utf-8")
        print(f"wrote {args.output}: {len(rows)} row(s)")
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
